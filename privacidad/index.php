      <article class="zd-legal-content">
        <p>ZentDigital respeta la privacidad de las personas que visitan su sitio web, realizan consultas comerciales o interactúan con sus servicios digitales.</p>
        <p>La presente Política de Privacidad explica qué información puede ser tratada, con qué finalidad, cómo se protege y cuáles son los derechos de las personas respecto de sus datos.</p>

        <section id="responsable" class="zd-legal-section"><h2><span>01</span>Responsable del tratamiento</h2>
          <p>El responsable del tratamiento de los datos personales recopilados a través de este sitio es <strong>ZentDigital</strong>, empresa dedicada al desarrollo e ingeniería de software.</p>
          <p>Sitio web: <strong>www.zentdigital.cl</strong></p>
          <p>Contacto para asuntos relacionados con privacidad y datos personales:</p>
          <p><span class="zd-legal-placeholder">contacto@zentdigital.cl</span></p>
        </section>

        <section id="informacion" class="zd-legal-section"><h2><span>02</span>Información que podemos recopilar</h2>
          <p>ZentDigital puede recopilar información proporcionada voluntariamente por una persona al:</p>
          <ul><li>completar un formulario de contacto;</li><li>solicitar información o una cotización;</li><li>comunicarse mediante los canales disponibles en el sitio;</li><li>iniciar una relación comercial o contractual con ZentDigital.</li></ul>
          <p>Esta información puede incluir nombre, correo electrónico, número de contacto, empresa u organización, descripción de un proyecto y cualquier otro antecedente que la persona decida entregar voluntariamente.</p>
          <p>El sitio puede además procesar información técnica básica necesaria para su funcionamiento y seguridad, como dirección IP, navegador, dispositivo, fecha y hora de acceso y registros técnicos del servidor.</p>
        </section>

        <section id="finalidades" class="zd-legal-section"><h2><span>03</span>Finalidades del tratamiento</h2>
          <p>Los datos personales serán utilizados únicamente para finalidades relacionadas con los servicios de ZentDigital, entre ellas:</p>
          <ul><li>responder consultas y solicitudes;</li><li>preparar propuestas o cotizaciones;</li><li>gestionar relaciones comerciales;</li><li>prestar los servicios contratados;</li><li>mantener la seguridad y funcionamiento del sitio;</li><li>cumplir obligaciones legales o contractuales;</li><li>mejorar la calidad de los servicios y la experiencia del sitio.</li></ul>
          <div class="zd-legal-callout"><p><strong>ZentDigital no vende datos personales</strong> ni los utiliza para finalidades incompatibles con aquellas para las cuales fueron recopilados.</p></div>
        </section>

        <section id="google" class="zd-legal-section"><h2><span>04</span>Integraciones con servicios de Google</h2>
          <p>ZentDigital puede utilizar servicios y APIs de Google para funciones específicas asociadas a su propia presencia digital.</p>
          <p>En particular, el sitio puede utilizar <strong>Google Business Profile APIs</strong> mediante autorización OAuth para acceder a información correspondiente al Perfil de Negocio de ZentDigital.</p>
          <p>Esta integración puede permitir consultar información como:</p>
          <ul><li>datos generales del Perfil de Negocio;</li><li>calificación promedio;</li><li>cantidad total de reseñas;</li><li>reseñas publicadas en el perfil;</li><li>nombre público del autor de una reseña;</li><li>puntuación, comentario y fecha de publicación;</li><li>respuestas públicas realizadas por ZentDigital.</li></ul>
          <p>El acceso se utiliza exclusivamente para administrar y mostrar información correspondiente al propio Perfil de Negocio de ZentDigital.</p>
          <p>ZentDigital no utiliza los datos obtenidos mediante las APIs de Google para publicidad, elaboración de perfiles, venta de información ni transferencia a terceros con fines comerciales.</p>
          <p>El uso y transferencia de información recibida desde las APIs de Google se realizará de acuerdo con la Google API Services User Data Policy, incluidos sus requisitos de Limited Use.</p>
          <div class="zd-legal-related"><a href="/uso-datos-google/">Ver Uso de Datos de Google <i class="bi bi-arrow-right"></i></a><a href="/terminos/">Ver Términos de Uso <i class="bi bi-arrow-right"></i></a></div>
        </section>

        <section id="oauth" class="zd-legal-section"><h2><span>05</span>Autorización mediante Google OAuth</h2>
          <div class="zd-legal-callout"><p>Cuando una integración con Google requiera autorización, esta se realizará mediante OAuth 2.0.</p><p>ZentDigital no solicita ni almacena la contraseña de la cuenta Google utilizada para autorizar el acceso.</p></div>
          <p>Google administra directamente el proceso de autenticación y autorización.</p>
          <p>La autorización concedida puede ser revocada en cualquier momento desde la configuración de seguridad de la cuenta Google correspondiente.</p>
          <p>Cuando el acceso sea revocado, ZentDigital dejará de realizar nuevas solicitudes que requieran dicha autorización.</p>
        </section>

        <section id="conservacion" class="zd-legal-section"><h2><span>06</span>Almacenamiento y conservación</h2>
          <p>Los datos serán conservados únicamente durante el período necesario para cumplir la finalidad para la cual fueron recopilados o mientras exista una obligación legal o contractual que justifique su conservación.</p>
          <p>Cuando se utilicen APIs externas, ZentDigital podrá mantener copias temporales o datos en caché cuando ello sea necesario para mejorar el rendimiento del sitio y reducir solicitudes innecesarias.</p>
          <p>Los datos almacenados temporalmente serán actualizados o eliminados cuando dejen de ser necesarios.</p>
        </section>

        <section id="seguridad" class="zd-legal-section"><h2><span>07</span>Seguridad</h2>
          <p>ZentDigital adopta medidas técnicas y organizativas razonables destinadas a evitar accesos no autorizados, pérdida, alteración, divulgación o uso indebido de información.</p>
          <p>Las credenciales privadas, secretos de cliente, tokens de acceso y otros elementos de autenticación asociados a integraciones externas deberán mantenerse en entornos privados del servidor y no exponerse públicamente en el código del navegador.</p>
          <p>Ningún sistema conectado a Internet puede garantizar seguridad absoluta, pero ZentDigital aplicará medidas proporcionales a la naturaleza de los datos tratados.</p>
        </section>

        <section id="terceros" class="zd-legal-section"><h2><span>08</span>Servicios de terceros</h2>
          <p>El sitio puede utilizar servicios proporcionados por terceros necesarios para su funcionamiento, infraestructura, comunicación o integraciones.</p>
          <p>Cada proveedor puede estar sujeto a sus propias políticas de privacidad y condiciones de servicio.</p>
          <p>Cuando corresponda, ZentDigital procurará utilizar proveedores que ofrezcan medidas adecuadas de seguridad y protección de datos.</p>
        </section>

        <section id="cookies" class="zd-legal-section"><h2><span>09</span>Cookies y tecnologías similares</h2>
          <p>ZentDigital puede utilizar cookies estrictamente necesarias para el funcionamiento técnico del sitio.</p>
          <p>Si en el futuro se incorporan herramientas de analítica, publicidad o seguimiento que requieran consentimiento conforme a la normativa aplicable, se informará a las personas usuarias y se implementarán los mecanismos correspondientes antes de su utilización.</p>
        </section>

        <section id="derechos" class="zd-legal-section"><h2><span>10</span>Derechos de las personas</h2>
          <p>Las personas pueden solicitar información sobre sus datos personales y, cuando corresponda conforme a la legislación aplicable, ejercer sus derechos de acceso, rectificación, eliminación o supresión, oposición, bloqueo y demás derechos reconocidos legalmente.</p>
          <p>Desde la entrada en vigencia de la Ley N.º 21.719 serán aplicables además los derechos y procedimientos contemplados por la nueva regulación chilena de protección de datos personales.</p>
          <div class="zd-legal-callout"><p>Las solicitudes pueden enviarse a:</p><p><span class="zd-legal-placeholder">contacto@zentdigital.cl</span></p><p>ZentDigital podrá solicitar información razonablemente necesaria para verificar la identidad de quien realiza la solicitud antes de entregar o modificar información personal.</p></div>
        </section>

        <section id="menores" class="zd-legal-section"><h2><span>11</span>Datos de menores de edad</h2>
          <p>Los servicios de ZentDigital están orientados principalmente a empresas, organizaciones y personas adultas que solicitan servicios profesionales.</p>
          <p>ZentDigital no busca recopilar intencionalmente información personal de niños, niñas o adolescentes a través de este sitio.</p>
        </section>

        <section id="transferencias" class="zd-legal-section"><h2><span>12</span>Transferencias de datos</h2>
          <p>Algunos proveedores tecnológicos utilizados por ZentDigital pueden procesar información utilizando infraestructura localizada fuera de Chile.</p>
          <p>Cuando corresponda, ZentDigital procurará que dichas transferencias se realicen bajo condiciones compatibles con la legislación aplicable y con medidas adecuadas de protección.</p>
        </section>

        <section id="cambios" class="zd-legal-section"><h2><span>13</span>Cambios a esta política</h2>
          <p>ZentDigital podrá actualizar esta Política de Privacidad cuando cambien sus servicios, integraciones tecnológicas, obligaciones legales o prácticas de tratamiento de datos.</p>
          <p>La versión vigente estará permanentemente disponible en este sitio y señalará su fecha de última actualización.</p>
        </section>

        <section id="contacto" class="zd-legal-section"><h2><span>14</span>Contacto</h2>
          <p>Para consultas relacionadas con privacidad, protección de datos o ejercicio de derechos:</p>
          <p><strong>ZentDigital</strong><br>www.zentdigital.cl</p>
          <p><span class="zd-legal-placeholder">contacto@zentdigital.cl</span></p>
        </section>
